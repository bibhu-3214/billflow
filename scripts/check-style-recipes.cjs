const fs = require('node:fs');
const path = require('node:path');
const ts = require('typescript');
const root = path.resolve(__dirname, '..');
const recipePath = path.join(root, 'src/styles/recipes.ts');
const source = ts.createSourceFile(recipePath, fs.readFileSync(recipePath, 'utf8'), ts.ScriptTarget.Latest, true);
const properties = [];
function visitRecipe(node) {
    if (ts.isPropertyAssignment(node) && ts.isStringLiteral(node.name) && ts.isStringLiteral(node.initializer)) properties.push(node);
    ts.forEachChild(node, visitRecipe);
}
visitRecipe(source);
const needed = new Set();
function scan(folder) {
    for (const entry of fs.readdirSync(folder, { withFileTypes: true })) {
        const file = path.join(folder, entry.name);
        if (entry.isDirectory()) { if (file !== path.join(root, 'src/styles')) scan(file); continue; }
        if (!/\.(ts|tsx)$/.test(file) || /\.test\./.test(file)) continue;
        const workspace = file.startsWith(path.join(root, 'src/components/Dashboard') + path.sep);
        const ast = ts.createSourceFile(file, fs.readFileSync(file, 'utf8'), ts.ScriptTarget.Latest, true);
        function visit(node) {
            if (ts.isStringLiteralLike(node) || ts.isTemplateHead(node) || ts.isTemplateMiddle(node) || ts.isTemplateTail(node)) {
                let parent = node.parent;
                let expandedInWorkspace = false;
                while (workspace && parent) {
                    if (ts.isCallExpression(parent) && ts.isIdentifier(parent.expression) && parent.expression.text === 'ui') { expandedInWorkspace = true; break; }
                    parent = parent.parent;
                }
                if (!expandedInWorkspace) {
                    const tokens = node.text.split(/\s+/);
                    for (const property of properties) if (tokens.includes(property.name.text)) needed.add(property.name.text);
                }
            }
            ts.forEachChild(node, visit);
        }
        visit(ast);
    }
}
scan(path.join(root, 'src'));
function render(name, nodes) {
    return '// Generated by scripts/check-style-recipes.cjs --write. Do not edit by hand.\nexport const ' + name + ': Record<string, string> = {\n' + nodes.map(node => '    ' + node.getText(source) + ',').join('\n') + '\n};\n';
}
const outputs = [
    ['recipes.public.ts', render('publicRecipes', properties.filter(node => needed.has(node.name.text)))],
    ['recipes.workspace.ts', render('workspaceRecipes', properties.filter(node => !needed.has(node.name.text)))],
];
for (const [name, generated] of outputs) {
    const target = path.join(root, 'src/styles', name);
    if (process.argv.includes('--write')) fs.writeFileSync(target, generated);
    else if (!fs.existsSync(target) || fs.readFileSync(target, 'utf8') !== generated) {
        console.error('Style coverage changed. Run node scripts/check-style-recipes.cjs --write.'); process.exitCode = 1;
    }
}
console.log('Public/shared recipes: ' + needed.size + '/' + properties.length + '; remaining recipes are deferred without duplication.');
